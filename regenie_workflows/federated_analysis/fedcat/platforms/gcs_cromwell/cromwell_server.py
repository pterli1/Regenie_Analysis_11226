"""`fedcat cromwell`: set up, start, check and stop a Cromwell server for the `local_cromwell` backend.

`cromwell.conf` is generated by `wb cromwell generate-config` (a Google Batch backend
using a workspace bucket) with `FEDCAT_SETTINGS` appended. The database location and
port are passed as `-D` options when the server starts, so the file has nothing
specific to one machine.
"""

from __future__ import annotations

import json
import os
import signal
import subprocess
import tempfile
import time
import urllib.error
import urllib.request
from collections import deque
from pathlib import Path

from loguru import logger

DEFAULT_PORT = 8000
CONF_NAME = "cromwell.conf"
LOG_NAME = "cromwell.log"
PID_NAME = "cromwell.pid"
DB_DIR_NAME = "db"

# Appended to the generated config; later HOCON blocks merge over earlier ones
FEDCAT_SETTINGS = """
# ── fedcat additions ─────────────────────────────────────────────────────────
# fedcat calls the REST API without authentication, so serve on this machine only.
webservice {
  interface = "127.0.0.1"
}

# File-backed database, so submitted workflows survive a server restart and fedcat
# can keep polling them. The file location is passed at launch (-Ddatabase.db.url).
database {
  profile = "slick.jdbc.HsqldbProfile$"
  db {
    driver = "org.hsqldb.jdbcDriver"
    connectionTimeout = 120000
    numThreads = 1
  }
}

# fedcat leaves completed tasks out of a resubmission itself.
call-caching {
  enabled = false
}

# Reading the task statuses of a large scatter is one metadata request, which can
# exceed Cromwell's 40s default. fedcat's client waits for the same length of time.
akka.http.server {
  request-timeout = 300s
  idle-timeout = 310s
}

# Cromwell <=92's default Batch helper image (cloud-sdk:461.0.0-alpine) has been
# deleted by Google's 1-year image retention, so every task fails at startup
# (cromwell#7899). A floating tag does not expire. It must be a Debian image: Batch
# sets CLOUDSDK_PYTHON=/usr/bin/python3, which alpine images lack, and Cromwell <=92
# leaves it set for helper runnables, so gsutil would fail during localization.
google {
  cloud-sdk-image-url = "gcr.io/google.com/cloudsdktool/google-cloud-cli:slim"
}
"""


class CromwellServerError(RuntimeError):
    """The Cromwell server could not be set up, started or stopped."""


def server_url(port: int = DEFAULT_PORT) -> str:
    """Return the URL of a server on this machine."""
    return f"http://localhost:{port}"


def db_url(directory: Path) -> str:
    """Return the JDBC URL of the HSQLDB file database under `directory`, set up for large workflows as Cromwell advises."""
    return (
        f"jdbc:hsqldb:file:{directory / DB_DIR_NAME / 'cromwell'};shutdown=false;"
        "hsqldb.default_table_type=cached;hsqldb.tx=mvcc;hsqldb.large_data=true;"
        "hsqldb.lob_compressed=true;hsqldb.script_format=3"
    )


def write_config(directory: Path, bucket_id: str, concurrent_job_limit: int, *, force: bool = False) -> Path:
    """Generate `cromwell.conf` with `wb cromwell generate-config` and append `FEDCAT_SETTINGS`.

    Args:
        directory: Server directory, created if needed.
        bucket_id: Workspace bucket for Cromwell's execution files.
        concurrent_job_limit: Most tasks Cromwell runs at once.
        force: Replace an existing config.

    Returns:
        The config file.

    Raises:
        CromwellServerError: If the config exists without `force`, or `wb` is missing or fails.
    """
    conf = directory / CONF_NAME
    if conf.exists() and not force:
        raise CromwellServerError(f"{conf} already exists; pass --force to regenerate it")
    directory.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [
            "wb",
            "cromwell",
            "generate-config",
            f"--workspace-bucket-name={bucket_id}",
            f"--concurrent-job-limit={concurrent_job_limit}",
            f"--dir={tmp}",
        ]
        try:
            subprocess.run(cmd, check=True, text=True, capture_output=True)
        except FileNotFoundError as exc:
            raise CromwellServerError("'wb' not found; run this inside a Workbench app") from exc
        except subprocess.CalledProcessError as exc:
            raise CromwellServerError(f"wb cromwell generate-config failed: {exc.stderr.strip()}") from exc
        generated = (Path(tmp) / CONF_NAME).read_text()
    conf.write_text(f"{generated.rstrip()}\n{FEDCAT_SETTINGS}")
    return conf


def _get_json(url: str, timeout: float = 5) -> dict | None:
    """GET a URL as JSON; an HTTP error gives `{"unhealthy": body}`, and None means nothing is listening."""
    try:
        with urllib.request.urlopen(url, timeout=timeout) as resp:
            return json.loads(resp.read() or b"{}")
    except urllib.error.HTTPError as exc:
        # /engine/v1/status answers 500 with per-subsystem detail while unhealthy
        body = exc.read()
        try:
            return {"unhealthy": json.loads(body or b"{}")}
        except json.JSONDecodeError:
            return {"unhealthy": body.decode(errors="replace")}
    except (urllib.error.URLError, ConnectionError, TimeoutError):
        return None


def server_status(port: int = DEFAULT_PORT) -> dict | None:
    """Return a local server's engine status and backends.

    Args:
        port: Server port.

    Returns:
        `{"engine": ..., "backends": ...}`, `{"unhealthy": ...}` while unhealthy, or None
        if no server is listening.
    """
    status = _get_json(f"{server_url(port)}/engine/v1/status")
    if status is None or "unhealthy" in status:
        return status
    return {"engine": status, "backends": _get_json(f"{server_url(port)}/api/workflows/v1/backends") or {}}


def _alive(pid: int) -> bool:
    """Return whether a process is running."""
    try:
        # Reap it if it is our own exited child, which would otherwise linger as a zombie
        if os.waitpid(pid, os.WNOHANG)[0] == pid:
            return False
    except ChildProcessError:
        pass
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        pass
    return True


def _read_pid(directory: Path) -> int | None:
    """Return the pid of the running server started from `directory`, or None."""
    try:
        pid = int((directory / PID_NAME).read_text().strip())
    except (OSError, ValueError):
        return None
    return pid if _alive(pid) else None


def _log_tail(directory: Path, lines: int = 30) -> str:
    """Return the last lines of the server log, or `""` if it cannot be read."""
    try:
        with (directory / LOG_NAME).open(errors="replace") as fh:
            return "".join(deque(fh, maxlen=lines))
    except OSError:
        return ""


# How often start/stop check on the server while waiting for it
START_POLL_SECONDS = 3.0
STOP_POLL_SECONDS = 2.0


def start_server(
    directory: Path,
    *,
    port: int = DEFAULT_PORT,
    memory: str = "16g",
    cromwell: str = "cromwell",
    timeout: float = 300,
) -> dict:
    """Start Cromwell in server mode in the background and wait until it is healthy.

    Does nothing if a server already answers on `port`.

    Args:
        directory: Server directory holding `cromwell.conf`; the database, log and
            pid file are written there.
        port: Port to serve on.
        memory: JVM maximum heap, e.g. `"16g"`.
        cromwell: The `cromwell` command, or a `cromwell.jar` path to run with `java -jar`.
        timeout: Seconds to wait for the server to become healthy.

    Returns:
        The [`server_status`][fedcat.platforms.gcs_cromwell.cromwell_server.server_status].

    Raises:
        CromwellServerError: If there is no config, Cromwell cannot be run, exits, or
            is not healthy within `timeout`.
    """
    conf = directory / CONF_NAME
    if not conf.is_file():
        raise CromwellServerError(f"{conf} not found; run 'fedcat cromwell setup' first")
    if (status := server_status(port)) is not None:
        logger.info(f"A Cromwell server is already answering on {server_url(port)}")
        return status

    (directory / DB_DIR_NAME).mkdir(parents=True, exist_ok=True)
    jvm_opts = [
        f"-Xmx{memory}",
        f"-Dconfig.file={conf.resolve()}",
        f"-Dwebservice.port={port}",
        f"-Ddatabase.db.url={db_url(directory.resolve())}",
    ]
    if cromwell.endswith(".jar"):
        cmd = ["java", *jvm_opts, "-jar", cromwell, "server"]
    else:
        # The Workbench/Bioconda wrapper passes leading -X/-D options to the JVM
        cmd = [cromwell, *jvm_opts, "server"]

    log = (directory / LOG_NAME).open("ab")
    try:
        proc = subprocess.Popen(
            cmd, stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, start_new_session=True
        )
    except FileNotFoundError as exc:
        raise CromwellServerError(f"cannot run {cmd[0]!r}; pass --cromwell with the command or jar path") from exc
    finally:
        log.close()
    (directory / PID_NAME).write_text(f"{proc.pid}\n")
    logger.info(f"Started Cromwell (pid {proc.pid}); log: {directory / LOG_NAME}")

    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise CromwellServerError(
                f"Cromwell exited with code {proc.returncode} during startup. Log tail:\n{_log_tail(directory)}"
            )
        status = server_status(port)
        if status is not None and "unhealthy" not in status:
            return status
        time.sleep(START_POLL_SECONDS)
    raise CromwellServerError(
        f"Cromwell did not become healthy within {timeout:.0f}s (still starting, pid {proc.pid}); "
        f"check 'fedcat cromwell status' or {directory / LOG_NAME}"
    )


def stop_server(directory: Path, *, timeout: float = 120) -> bool:
    """Stop the server started from `directory` with SIGTERM, and wait for it to exit.

    Running workflows are not aborted, and resume when the server restarts.

    Args:
        directory: Server directory.
        timeout: Seconds to wait for the server to exit.

    Returns:
        False if no server was running.

    Raises:
        CromwellServerError: If the server is still running after `timeout`.
    """
    pid = _read_pid(directory)
    if pid is None:
        (directory / PID_NAME).unlink(missing_ok=True)
        return False
    os.kill(pid, signal.SIGTERM)
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if _read_pid(directory) is None:
            (directory / PID_NAME).unlink(missing_ok=True)
            return True
        time.sleep(STOP_POLL_SECONDS)
    raise CromwellServerError(f"Cromwell (pid {pid}) still running {timeout:.0f}s after SIGTERM")


def describe(status: dict | None, port: int = DEFAULT_PORT) -> tuple[bool, list[str]]:
    """Describe a server status for `fedcat cromwell status`.

    Args:
        status: From [`server_status`][fedcat.platforms.gcs_cromwell.cromwell_server.server_status].
        port: Server port.

    Returns:
        `(ok, lines)`: whether the server is healthy and runs tasks on Google Batch,
        and lines explaining why.
    """
    url = server_url(port)
    if status is None:
        return False, [f"No Cromwell server answering on {url}; start one with 'fedcat cromwell start'"]
    if "unhealthy" in status:
        return False, [f"Cromwell on {url} is unhealthy: {status['unhealthy']}"]
    backends = status.get("backends", {})
    default = backends.get("defaultBackend", "?")
    lines = [f"Cromwell healthy on {url}; backends {backends.get('supportedBackends', [])}, default {default!r}"]
    if default == "Local":
        lines.append("Default backend is 'Local': tasks would run on this machine. Was cromwell.conf loaded?")
        return False, lines
    return True, lines
